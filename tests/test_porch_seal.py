# node side: seal | open | vector, driven by argv. Errors print "ERR <kind>".
NODE_HARNESS = r"""
const P = require(process.env.SEAL_JS);
const fs = require('fs');
const [op, a, b, c, d, e] = process.argv.slice(1);
const hex = s => Uint8Array.from(Buffer.from(s, 'hex'));
function secret(s) { return s.startsWith('pw:') ? {password: s.slice(3)} : (s === '-' ? {} : {key: s}); }
(async () => {
  if (op === 'seal' || op === 'vector') {
    const opts = Object.assign({name: c, type: d}, secret(e || '-'));
    if (op === 'vector') { opts._prefix = hex(process.env.VEC_PREFIX); opts._salt = hex(process.env.VEC_SALT); }
    const src = op === 'vector' || process.env.AS_BYTES ? fs.readFileSync(a) : new Blob([fs.readFileSync(a)]);
    const s = new P.Sealer(src, opts);
    const fd = fs.openSync(b, 'wx', 0o600);
    let n = 0, first = true;
    for await (const piece of s) {
      if (first && piece.length !== 4160) throw new Error('first piece is not header + record 0');
      first = false;
      fs.writeSync(fd, piece); n += piece.length;
    }
    fs.closeSync(fd);
    if (n !== s.totalSize()) throw new Error('totalSize mismatch ' + n + ' ' + s.totalSize());
    console.log(s.key || 'password');
  } else if (op === 'open') {
    const buf = fs.readFileSync(a);
    const src = process.env.AS_BLOB ? new Blob([buf]) : buf;
    const r = await P.open(src, Object.assign({batch: 3}, secret(c)));
    const parts = [];
    for await (const chunk of r.chunks) parts.push(chunk);
    fs.writeFileSync(b, Buffer.concat(parts));
    console.log(JSON.stringify(r.meta));
  } else if (op === 'fragment') {
    console.log(JSON.stringify(P.keyFromFragment(a)));
  } else if (op === 'sizes') {
    const out = [];
    for (const n of JSON.parse(a)) out.push([P.ciphertextSize(n), P.plaintextSize(P.ciphertextSize(n))]);
    console.log(JSON.stringify(out));
  }
})().catch(err => { console.log('ERR ' + (err.kind || err.name) + ' ' + err.message); process.exit(3); });
"""


def node(*args, env=None):
    e = dict(os.environ, SEAL_JS=SEAL_JS, VEC_PREFIX=VEC_PREFIX.hex(), VEC_SALT=VEC_SALT.hex())
    e.update(env or {})
    p = subprocess.run([NODE, "-e", NODE_HARNESS, *args], capture_output=True, text=True,
                       env=e, timeout=120)
    return p.returncode, p.stdout.strip(), p.stderr


class Base(unittest.TestCase):

    def setUp(self):
        self.dir = tempfile.mkdtemp()
        self.addCleanup(shutil.rmtree, self.dir, True)

    def path(self, name):
        return os.path.join(self.dir, name)

    def write(self, name, data):
        with open(self.path(name), "wb") as f:
            f.write(data)
        return self.path(name)

    def read(self, name):
        with open(self.path(name), "rb") as f:
            return f.read()

    def seal(self, data, name="f.pseal", **kw):
        key = ps.seal_file(io.BytesIO(data), self.path(name), "f.bin", "application/x-test", **kw)
        return self.path(name), key

    def open_all(self, path, **kw):
        meta, it = ps.open_file(path, **kw)
        return meta, b"".join(it)

    def assertOpenFails(self, path, kind, **kw):
        with self.assertRaises(ps.SealError) as cm:
            self.open_all(path, **kw)
        self.assertEqual(cm.exception.kind, kind, str(cm.exception))


class FormatTests(Base):

    def test_header_layout(self):
        h = ps.build_header(ps.MODE_PASSWORD, bytes(range(16)), b"ABCDEFGH")
        self.assertEqual(len(h), 48)
        self.assertEqual(h[:8], bytes.fromhex("50534541 4C310A00"))
        self.assertEqual(h[8], 1)
        self.assertEqual(h[9], 1)
        self.assertEqual(h[34:38], struct.pack(">I", 65536))
        self.assertEqual(h[38:], bytes(10))
        self.assertEqual(ps.parse_header(h)["prefix"], b"ABCDEFGH")

    def test_offsets(self):
        self.assertEqual(ps.record_span(0, 10), (48, 4112))
        self.assertEqual(ps.record_span(1, 10), (4160, 26))
        size = 2 * R + 5
        self.assertEqual(ps.record_span(2, size), (4160 + R + 16, R + 16))
        self.assertEqual(ps.record_span(3, size), (4160 + 2 * (R + 16), 21))
        for size in (0, 1, R - 1, R, R + 1, 3 * R, 5 * 1024 * 1024 + 7):
            ct = ps.ciphertext_size(size)
            self.assertEqual(ct, 48 + 4112 + ps.record_count(size) * 16 + size)
            self.assertEqual(ps.plaintext_size(ct), size)
        for bad in (4159, 4160 + 16, 4160 + R + 16 + 10):
            with self.assertRaises(ps.SealError):
                ps.plaintext_size(bad)

    def test_meta_record(self):
        plain = ps.meta_plaintext("a.txt", "text/plain", 3)
        self.assertEqual(len(plain), 4096)
        self.assertEqual(ps.parse_meta(plain), {"name": "a.txt", "type": "text/plain", "size": 3})
        long = ps.parse_meta(ps.meta_plaintext("x" * 1000 + ".pdf", "application/pdf", 1))
        self.assertEqual(len(long["name"]), 255)
        self.assertTrue(long["name"].endswith(".pdf"))

    def test_vectors_python(self):
        for mode, kw in (("key", {"key": VEC_KEY}), ("password", {"password": VEC_PASSWORD,
                                                                  "_test_salt": VEC_SALT})):
            dst = self.path(mode)
            ps.seal_file(io.BytesIO(VEC_PLAIN), dst, "vector.txt", "text/plain",
                         _test_prefix=VEC_PREFIX, **kw)
            data = self.read(mode)
            self.assertEqual(data[:48].hex(), VEC[mode]["header"])
            self.assertEqual(data[4160:].hex(), VEC[mode]["record1"])
            self.assertEqual(hashlib.sha256(data).hexdigest(), VEC[mode]["sha256"])
            okw = {"key_b64": ps.b64url(VEC_KEY)} if mode == "key" else {"password": VEC_PASSWORD}
            self.assertEqual(self.open_all(dst, **okw)[1], VEC_PLAIN)

    def test_missing_cryptography_hint(self):
        import builtins
        real = builtins.__import__

        def fake(name, *a, **kw):
            if name.startswith("cryptography"):
                raise ImportError(name)
            return real(name, *a, **kw)
        builtins.__import__ = fake
        try:
            with self.assertRaises(ps.SealUnavailable) as cm:
                ps._aesgcm(bytes(32))
            self.assertFalse(ps.available())
        finally:
            builtins.__import__ = real
        self.assertIn("sudo apt install python3-cryptography", str(cm.exception))


class PythonRoundTrip(Base):

    def test_sizes(self):
        for size in (0, 1, R - 1, R, R + 1, 3 * R + 17):
            data = os.urandom(size)
            path, key = self.seal(data, f"s{size}")
            self.assertEqual(os.path.getsize(path), ps.ciphertext_size(size))
            self.assertEqual(os.stat(path).st_mode & 0o777, 0o600)
            meta, out = self.open_all(path, key_b64=key)
            self.assertEqual(out, data)
            self.assertEqual(meta["size"], size)

    def test_path_source_and_key_reuse(self):
        src = self.write("in.bin", b"abc" * 30000)
        key = ps.b64url(os.urandom(32))
        self.assertEqual(ps.seal_file(src, self.path("o"), "in.bin", "x/y", key=key), key)
        self.assertEqual(self.open_all(self.path("o"), key_b64=key)[1], b"abc" * 30000)
        with self.assertRaises(FileExistsError):              # O_EXCL: never overwrites
            ps.seal_file(src, self.path("o"), "in.bin", "x/y")

    def test_password_mode(self):
        path, key = self.seal(b"secret stuff" * 10000, password="pa55word!")
        self.assertIsNone(key)
        self.assertEqual(ps.info(path)["mode"], "password")
        self.assertEqual(self.open_all(path, password="pa55word!")[1], b"secret stuff" * 10000)
        self.assertOpenFails(path, "key", password="pa55word?")
        self.assertOpenFails(path, "key")                       # no password given
        with open(path, "rb") as f:
            self.assertEqual(f.read()[10:26] != bytes(16), True)    # a real salt

    def test_wrong_key(self):
        path, key = self.seal(b"x" * 100)
        self.assertOpenFails(path, "key", key_b64=ps.b64url(os.urandom(32)))
        self.assertOpenFails(path, "key", key_b64="short")
        self.assertOpenFails(path, "key")


def _tampered(data, how):
    """Variants of a 3-record sealed file (record 3 is short)."""
    b = bytearray(data)
    s1, l1 = ps.record_span(1, 2 * R + 100)
    s2, l2 = ps.record_span(2, 2 * R + 100)
    s3, l3 = ps.record_span(3, 2 * R + 100)
    if how == "content":
        b[s2 + 100] ^= 1
    elif how == "tag":
        b[s3 + l3 - 1] ^= 1
    elif how == "meta":
        b[200] ^= 1
    elif how == "magic":
        b[0] ^= 1
    elif how == "version":
        b[8] = 2
    elif how == "record_size":
        b[36] ^= 1
    elif how == "salt_in_key_mode":
        b[12] = 1
    elif how == "prefix":
        b[30] ^= 1
    elif how == "reserved":
        b[40] = 1
    elif how == "drop_last":
        del b[s3:]
    elif how == "drop_byte":
        del b[-1:]
    elif how == "trailing":
        b += b"\x00"
    elif how == "trailing_record":
        b += b"\x00" * 40
    elif how == "reorder":
        b[s1:s1 + l1], b[s2:s2 + l2] = data[s2:s2 + l2], data[s1:s1 + l1]
    elif how == "truncate_header":
        del b[30:]
    return bytes(b)


EXPECT = {"content": "tamper", "tag": "tamper", "meta": "key", "magic": "format",
          "version": "format", "record_size": "format", "salt_in_key_mode": "format",
          "prefix": "key", "reserved": "format", "drop_last": "tamper", "drop_byte": "tamper",
          "trailing": "tamper", "trailing_record": "tamper", "reorder": "tamper",
          "truncate_header": "format"}


def _custom(path, key, size, flags, plain_meta_size=None):
    """A key-mode file whose record i is encrypted with final flag flags[i]
    (record 0 first): for final-flag misuse."""
    from cryptography.hazmat.primitives.ciphers.aead import AESGCM
    g = AESGCM(key)
    prefix = os.urandom(8)
    h = ps.build_header(ps.MODE_KEY, bytes(16), prefix)
    data = os.urandom(size)
    out = h + g.encrypt(ps.nonce(prefix, 0),
                        ps.meta_plaintext("c", "x/y", size if plain_meta_size is None
                                          else plain_meta_size), ps.aad(h, flags[0]))
    for i in range(1, ps.record_count(size) + 1):
        chunk = data[(i - 1) * R:i * R]
        out += g.encrypt(ps.nonce(prefix, i), chunk, ps.aad(h, flags[i]))
    with open(path, "wb") as f:
        f.write(out)


class FailClosed(Base):

    def setUp(self):
        super().setUp()
        self.plain = os.urandom(2 * R + 100)
        self.sealed, self.key = self.seal(self.plain)
        with open(self.sealed, "rb") as f:
            self.data = f.read()

    def test_tamper_cases(self):
        for how, kind in EXPECT.items():
            with self.subTest(how=how):
                p = self.write(f"t-{how}", _tampered(self.data, how))
                self.assertOpenFails(p, kind, key_b64=self.key)

    def test_iterator_fails_on_later_record(self):
        p = self.write("late", _tampered(self.data, "tag"))
        meta, it = ps.open_file(p, key_b64=self.key)
        self.assertEqual(len(next(it)), R)                     # records 1, 2 are fine
        self.assertEqual(len(next(it)), R)
        with self.assertRaises(ps.SealError) as cm:
            next(it)
        self.assertEqual(cm.exception.kind, "tamper")

    def test_final_flag_misuse(self):
        key = os.urandom(32)
        k = ps.b64url(key)
        good = self.path("good")
        _custom(good, key, 2 * R, [0, 0, 1])
        self.assertEqual(len(self.open_all(good, key_b64=k)[1]), 2 * R)
        cases = {
            "final_on_record1": [0, 1, 1],       # a final flag on a non-last record
            "no_final": [0, 0, 0],               # the last record is not marked final
            "final_on_meta": [1, 0, 1],          # record 0 claims to be last
        }
        for name, flags in cases.items():
            with self.subTest(name):
                p = self.path(name)
                _custom(p, key, 2 * R, flags)
                with self.assertRaises(ps.SealError):
                    self.open_all(p, key_b64=k)
        # empty file: record 0 must carry the final flag
        p = self.path("empty_nofinal")
        _custom(p, key, 0, [0])
        self.assertOpenFails(p, "key", key_b64=k)
        p = self.path("empty_ok")
        _custom(p, key, 0, [1])
        self.assertEqual(self.open_all(p, key_b64=k)[1], b"")

    def test_cli(self):
        src = self.write("cli.txt", b"hello cli\n")
        out = subprocess.run([sys.executable, os.path.join(LIB, "porch_seal.py"), "seal", src,
                              self.path("cli.pseal"), "--type", "text/plain"],
                             capture_output=True, text=True, timeout=60)
        self.assertEqual(out.returncode, 0, out.stderr)
        key = out.stdout.strip()
        p = subprocess.run([sys.executable, os.path.join(LIB, "porch_seal.py"), "open",
                            self.path("cli.pseal"), "-", "--key", key],
                           capture_output=True, timeout=60)
        self.assertEqual(p.stdout, b"hello cli\n")
        self.assertEqual(json.loads(p.stderr)["name"], "cli.txt")
        p = subprocess.run([sys.executable, os.path.join(LIB, "porch_seal.py"), "open",
                            self.write("bad", _tampered(self.data, "tag")), self.path("bad.out"),
                            "--key", self.key], capture_output=True, text=True, timeout=60)
        self.assertEqual(p.returncode, 1)
        self.assertIn("tamper", p.stderr)
        self.assertFalse(os.path.exists(self.path("bad.out")))   # no half-checked plaintext


@unittest.skipUnless(NODE, "node is not installed")
class CrossImplementation(Base):

    def py_to_node(self, data, password=None, blob=False):
        path, key = self.seal(data, password=password)
        rc, out, err = node("open", path, self.path("node.out"),
                            ("pw:" + password) if password else key,
                            env={"AS_BLOB": "1"} if blob else None)
        self.assertEqual(rc, 0, out + err)
        self.assertEqual(json.loads(out)["size"], len(data))
        self.assertEqual(self.read("node.out"), data)
        os.unlink(self.path("node.out"))
        os.unlink(path)

    def node_to_py(self, data, password=None, as_bytes=False):
        src = self.write("plain.in", data)
        rc, out, err = node("seal", src, self.path("n.pseal"), "plain.in", "application/x-test",
                            ("pw:" + password) if password else "-",
                            env={"AS_BYTES": "1"} if as_bytes else None)
        self.assertEqual(rc, 0, out + err)
        kw = {"password": password} if password else {"key_b64": out}
        meta, got = self.open_all(self.path("n.pseal"), **kw)
        self.assertEqual(got, data)
        self.assertEqual(meta, {"name": "plain.in", "type": "application/x-test", "size": len(data)})
        os.unlink(self.path("n.pseal"))

    def test_sizes_both_ways(self):
        for size in (0, 1, R, R + 1):
            with self.subTest(size=size):
                data = os.urandom(size)
                self.py_to_node(data)
                self.node_to_py(data)

    def test_5mb_both_ways(self):
        data = os.urandom(5 * 1024 * 1024 + 3)
        self.py_to_node(data, blob=True)
        self.node_to_py(data)

    def test_password_both_ways(self):
        data = os.urandom(R + 5)
        self.py_to_node(data, password="hunter22 hunter22")
        self.node_to_py(data, password="hunter22 hunter22", as_bytes=True)

    def test_vectors_node(self):
        src = self.write("vec.txt", VEC_PLAIN)
        for mode, secret in (("key", ps.b64url(VEC_KEY)), ("password", "pw:" + VEC_PASSWORD)):
            with self.subTest(mode=mode):
                dst = self.path("vec-" + mode)
                rc, out, err = node("vector", src, dst, "vector.txt", "text/plain", secret)
                self.assertEqual(rc, 0, out + err)
                data = self.read("vec-" + mode)
                self.assertEqual(data[:48].hex(), VEC[mode]["header"])
                self.assertEqual(data[4160:].hex(), VEC[mode]["record1"])
                self.assertEqual(hashlib.sha256(data).hexdigest(), VEC[mode]["sha256"])

    def test_node_fails_closed(self):
        plain = os.urandom(2 * R + 100)
        path, key = self.seal(plain)
        with open(path, "rb") as f:
            data = f.read()
        for how, kind in EXPECT.items():
            with self.subTest(how=how):
                p = self.write(f"t-{how}", _tampered(data, how))
                rc, out, _ = node("open", p, self.path(f"o-{how}"), key)
                self.assertEqual(rc, 3, out)
                self.assertTrue(out.startswith(f"ERR {kind} "), (how, out))
        rc, out, _ = node("open", path, self.path("wrong"), ps.b64url(os.urandom(32)))
        self.assertTrue(out.startswith("ERR key "), out)
        pw_path, _ = self.seal(plain, "pw.pseal", password="right-password")
        rc, out, _ = node("open", pw_path, self.path("wrongpw"), "pw:wrong-password")
        self.assertTrue(out.startswith("ERR key "), out)
        key2 = os.urandom(32)
        p = self.path("flag")
        _custom(p, key2, 2 * R, [0, 1, 1])
        rc, out, _ = node("open", p, self.path("flag.out"), ps.b64url(key2))
        self.assertTrue(out.startswith("ERR tamper "), out)
        _custom(p + "2", key2, 2 * R, [0, 0, 0])
        rc, out, _ = node("open", p + "2", self.path("flag2.out"), ps.b64url(key2))
        self.assertTrue(out.startswith("ERR tamper "), out)

    def test_fragment_and_sizes(self):
        k = ps.b64url(os.urandom(32))
        for frag, want in ((f"#k={k}", k), (f"#x=1&k={k}", k), ("#k=short", None), ("", None),
                           (f"#k={k}=", None)):
            rc, out, _ = node("fragment", frag)
            self.assertEqual(json.loads(out), want, frag)
        sizes = [0, 1, R - 1, R, R + 1, 10 * R + 3]
        rc, out, _ = node("sizes", json.dumps(sizes))
        self.assertEqual(json.loads(out), [[ps.ciphertext_size(n), n] for n in sizes])


